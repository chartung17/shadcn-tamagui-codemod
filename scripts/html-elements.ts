import * as dom from '@tamagui/dom'

// @tamagui/dom's .d.ts files use extensionless relative re-exports, which
// NodeNext resolution cannot follow, so describe the parts used here.
interface TagRow {
  backing: string
  display: string
  native: string
  note?: string
}
const { NATIVE_INPUT_TYPES, TAGS } = dom as unknown as {
  NATIVE_INPUT_TYPES: readonly string[]
  TAGS: Record<string, TagRow>
}

/** The `html.*` element table, derived from @tamagui/dom's DOM contract tables. */
export function buildHtmlElementsData(version: string) {
  const tags: Record<
    string,
    { backing: string; display: string; nativeSupported: boolean; note?: string }
  > = {}
  for (const [tag, row] of Object.entries(TAGS).sort(([a], [b]) => a.localeCompare(b))) {
    tags[tag] = {
      backing: row.backing,
      display: row.display,
      nativeSupported: row.native !== 'none',
      ...(row.note ? { note: row.note } : {}),
    }
  }
  return {
    $comment: 'Generated by `pnpm generate:data` from @tamagui/dom. Do not edit by hand.',
    source: `@tamagui/dom@${version}`,
    tags,
    nativeInputTypes: [...NATIVE_INPUT_TYPES],
  }
}
