import { defaultConfig } from '@tamagui/config/v6'

type Config = {
  tokens: Record<string, Record<string, unknown>>
  themes: Record<string, Record<string, unknown>>
  media: Record<string, unknown>
  fonts: Record<
    string,
    { size: Record<string, unknown>; lineHeight: Record<string, unknown> }
  >
}

/**
 * Token, theme and media names of `@tamagui/config/v6`'s default config, which
 * the theme pass extends. The class analysis checks Tailwind values against
 * these names.
 */
export function buildConfigTokensData(version: string) {
  const config = defaultConfig as unknown as Config
  const keys = (record: Record<string, unknown> | undefined) => Object.keys(record ?? {})
  return {
    $comment:
      'Generated by `pnpm generate:data` from @tamagui/config/v6. Do not edit by hand.',
    source: `@tamagui/config@${version} (v6 defaultConfig)`,
    tokens: Object.fromEntries(
      Object.keys(config.tokens)
        .sort()
        .map((category) => [category, keys(config.tokens[category])]),
    ),
    fonts: Object.fromEntries(
      Object.entries(config.fonts).map(([name, font]) => [
        name,
        { size: keys(font.size), lineHeight: keys(font.lineHeight) },
      ]),
    ),
    themeKeys: keys(config.themes.light),
    media: keys(config.media),
  }
}
