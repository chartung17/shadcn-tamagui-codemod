import { toNativeColor } from './color.js'
import { lengthToPx, parseShadcnCss, resolveVars } from './css.js'

export interface ThemeNote {
  severity: 'warning' | 'info'
  construct: string
  reason: string
}

export interface GeneratedTheme {
  code: string
  /** Color keys added to every theme (`background`, `primary`, ...). */
  themeKeys: string[]
  notes: ThemeNote[]
}

const RADIUS_KEYS = ['xs', 'sm', 'md', 'lg', 'xl', '2xl', '3xl', '4xl']

function quote(value: string): string {
  return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
}

function key(name: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(name) ? name : quote(name)
}

function colors(
  vars: Record<string, string>,
  scope: Record<string, string>,
  label: string,
  notes: ThemeNote[],
): Map<string, string> {
  const out = new Map<string, string>()
  for (const [name, raw] of Object.entries(vars)) {
    const resolved = resolveVars(raw, scope)
    const color = toNativeColor(resolved)
    if (!color) {
      if (/^(var\(|oklch|oklab|lab|lch|color\()/.test(resolved)) {
        notes.push({
          severity: 'warning',
          construct: `--${name}`,
          reason: `${label}: \`${raw}\` could not be converted to a native color, so it was left out.`,
        })
      }
      continue
    }
    out.set(name, color.value)
  }
  return out
}

/**
 * Generate a `tamagui.config.ts` from a shadcn `globals.css`. The config is
 * `@tamagui/config/v6` with the shadcn colors added to every light and dark
 * theme (so `bg-primary` resolves), the shadcn radius scale, Tailwind's `2xl`
 * breakpoint, and the shadcn font families.
 */
export function generateTamaguiConfig(
  cssText: string,
  sourcePath: string,
): GeneratedTheme {
  const css = parseShadcnCss(cssText)
  const notes: ThemeNote[] = []
  const all = { ...css.light, ...css.theme }

  const light = colors(css.light, css.light, 'light', notes)
  const dark = colors(css.dark, { ...css.light, ...css.dark }, 'dark', notes)

  // `@theme { --color-brand: oklch(...) }` defines a color directly.
  for (const [name, raw] of Object.entries(css.theme)) {
    const m = /^color-(.+)$/.exec(name)
    if (!m || /var\(/.test(raw)) continue
    const color = toNativeColor(resolveVars(raw, all))
    if (color && !light.has(m[1]!)) {
      light.set(m[1]!, color.value)
      if (!dark.has(m[1]!)) dark.set(m[1]!, color.value)
    }
  }
  for (const name of light.keys()) {
    if (!dark.has(name)) {
      dark.set(name, light.get(name)!)
      if (Object.keys(css.dark).length) {
        notes.push({
          severity: 'info',
          construct: `--${name}`,
          reason: 'No `.dark` value; the dark theme uses the light value.',
        })
      }
    }
  }
  for (const name of dark.keys()) {
    if (!light.has(name)) light.set(name, dark.get(name)!)
  }

  const radius: [string, number][] = []
  for (const k of RADIUS_KEYS) {
    const raw = css.theme[`radius-${k}`]
    if (!raw) continue
    const px = lengthToPx(resolveVars(raw, all))
    if (px === undefined) {
      notes.push({
        severity: 'warning',
        construct: `--radius-${k}`,
        reason: `\`${raw}\` could not be evaluated to px.`,
      })
    } else {
      radius.push([k, px])
    }
  }

  const fonts: [string, string][] = []
  const sans = css.theme['font-sans'] && resolveVars(css.theme['font-sans'], all)
  const heading = css.theme['font-heading'] && resolveVars(css.theme['font-heading'], all)
  if (sans && !/var\(/.test(sans)) fonts.push(['body', sans])
  if (heading && !/var\(/.test(heading)) fonts.push(['heading', heading])
  else if (sans && !/var\(/.test(sans)) fonts.push(['heading', sans])
  if (fonts.length) {
    notes.push({
      severity: 'warning',
      construct: 'fonts',
      reason: `Font families (${[...new Set(fonts.map(([, f]) => f))].join('; ')}) must also be loaded on native (e.g. with expo-font) under the same names.`,
    })
  }

  const entries = (map: Map<string, string>) =>
    [...map].map(([name, value]) => `  ${key(name)}: ${quote(value)},`).join('\n')

  const code = `// Generated by shadcn-tamagui-codemod from ${sourcePath}.
// Re-run \`shadcn-tamagui-codemod --theme-css ${sourcePath}\` after changing the CSS.
import { defaultConfig } from '@tamagui/config/v6'
import { createTamagui } from 'tamagui'

/** shadcn :root colors (oklch converted for native). */
const light = {
${entries(light)}
}

/** shadcn .dark colors. */
const dark: typeof light = {
${entries(dark)}
}

type BaseThemes = typeof defaultConfig.themes

/** Every v6 theme gets the shadcn colors for its scheme, so sub-themes keep working. */
const themes = Object.fromEntries(
  Object.entries(defaultConfig.themes).map(([name, theme]) => [
    name,
    { ...theme, ...(name.startsWith('dark') ? dark : light) },
  ]),
) as { [K in keyof BaseThemes]: BaseThemes[K] & typeof light }

export const config = createTamagui({
  ...defaultConfig,
  themes,
  media: {
    ...defaultConfig.media,
    // Tailwind's 2xl breakpoint (v6 calls it xxl).
    '2xl': { minWidth: 1536 },
    'max-2xl': { maxWidth: 1535.98 },
  },
  tokens: {
    ...defaultConfig.tokens,
    radius: {
      ...defaultConfig.tokens.radius,
${radius.map(([k, px]) => `      ${key(k)}: ${px},`).join('\n')}
    },
  },
${
  fonts.length
    ? `  fonts: {
    ...defaultConfig.fonts,
${fonts.map(([name, family]) => `    ${name}: { ...defaultConfig.fonts.${name}, family: ${quote(family)} },`).join('\n')}
  },
`
    : ''
}})

export default config

export type Conf = typeof config

declare module 'tamagui' {
  interface TamaguiCustomConfig extends Conf {}
}
`
  return { code, themeKeys: [...light.keys()], notes }
}
